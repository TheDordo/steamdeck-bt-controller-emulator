DS4_INPUT_REPORT_SIZE = 64  # includes Report ID byte

# Button bits of the 64-byte input report (see ds4drv parse_report).
# Byte 5: low nibble = dpad, then square/cross/circle/triangle.
# Byte 6: L1/R1/L2/R2/Share/Options/L3/R3. Byte 7: PS + touchpad + counter.
DS4_BTN_SQUARE = 0x10
DS4_BTN_CROSS = 0x20
DS4_BTN_CIRCLE = 0x40
DS4_BTN_TRIANGLE = 0x80

DS4_BTN_L1 = 0x01
DS4_BTN_R1 = 0x02
DS4_BTN_L2 = 0x04
DS4_BTN_R2 = 0x08
DS4_BTN_SHARE = 0x10
DS4_BTN_OPTIONS = 0x20
DS4_BTN_L3 = 0x40
DS4_BTN_R3 = 0x80

DS4_BTN_PS = 0x01
DS4_BTN_TOUCHPAD = 0x02

# Gamepad index -> DS4 bit (matches InputHandler BUTTON_MAP order:
# A, B, X, Y, LB, RB, Back, Start, Guide, L3, R3)
DS4_BUTTON_MAP = {
    0: DS4_BTN_CROSS,      # A
    1: DS4_BTN_CIRCLE,     # B
    2: DS4_BTN_SQUARE,     # X
    3: DS4_BTN_TRIANGLE,   # Y
    4: DS4_BTN_L1,         # LB
    5: DS4_BTN_R1,         # RB
    6: DS4_BTN_SHARE,      # Back
    7: DS4_BTN_OPTIONS,     # Start
    8: DS4_BTN_PS,         # Guide
    9: DS4_BTN_L3,         # L3
    10: DS4_BTN_R3,        # R3
}


class Ds4ReportBuilder:
    """Builds 64-byte DualShock 4 USB input reports from the shared gamepad
    state model used across the app (11 buttons, 4 axes, 2 triggers, hat)."""

    DPAD_NEUTRAL = 8

    def __init__(self):
        self._buttons = 0              # 11-bit mask, same semantics as usb_gadget
        self._axes = [0, 0, 0, 0]      # -32768..32767
        self._triggers = [0, 0]        # 0..255
        self._hat = self.DPAD_NEUTRAL  # 0..7 directions, 8 = center
        self._counter = 0

    def set_button(self, index: int, pressed: bool) -> None:
        if 0 <= index < 11:
            if pressed:
                self._buttons |= (1 << index)
            else:
                self._buttons &= ~(1 << index)

    def set_axis(self, index: int, value: int) -> None:
        if 0 <= index < 4:
            self._axes[index] = max(-32768, min(32767, value))

    def set_trigger(self, index: int, value: int) -> None:
        if 0 <= index < 2:
            self._triggers[index] = max(0, min(255, value))

    def set_hat(self, value: int) -> None:
        if value == 0x0F:
            value = self.DPAD_NEUTRAL
        self._hat = value if 0 <= value <= 8 else self.DPAD_NEUTRAL

    def _pack_axis(self, value: int) -> int:
        """-32768..32767 -> 0..255 (127/128 center)."""
        return int(((value + 32768) / 65535.0) * 255.0)

    def build(self) -> bytes:
        report = bytearray(64)
        report[0] = 0x01  # Report ID

        report[1] = self._pack_axis(self._axes[0])   # left stick X
        report[2] = self._pack_axis(self._axes[1])   # left stick Y
        report[3] = self._pack_axis(self._axes[2])   # right stick X
        report[4] = self._pack_axis(self._axes[3])   # right stick Y

        # Byte 5: dpad (low nibble) + face buttons
        byte5 = self._hat & 0x0F
        if self._buttons & (1 << 2):
            byte5 |= DS4_BTN_SQUARE
        if self._buttons & (1 << 0):
            byte5 |= DS4_BTN_CROSS
        if self._buttons & (1 << 1):
            byte5 |= DS4_BTN_CIRCLE
        if self._buttons & (1 << 3):
            byte5 |= DS4_BTN_TRIANGLE
        report[5] = byte5

        # Byte 6: shoulders / sticks / system buttons
        byte6 = 0
        if self._buttons & (1 << 4):
            byte6 |= DS4_BTN_L1
        if self._buttons & (1 << 5):
            byte6 |= DS4_BTN_R1
        if self._triggers[0] > 0:
            byte6 |= DS4_BTN_L2
        if self._triggers[1] > 0:
            byte6 |= DS4_BTN_R2
        if self._buttons & (1 << 6):
            byte6 |= DS4_BTN_SHARE
        if self._buttons & (1 << 7):
            byte6 |= DS4_BTN_OPTIONS
        if self._buttons & (1 << 9):
            byte6 |= DS4_BTN_L3
        if self._buttons & (1 << 10):
            byte6 |= DS4_BTN_R3
        report[6] = byte6

        # Byte 7: PS/touch + report counter (bits 2-7)
        byte7 = 0
        if self._buttons & (1 << 8):
            byte7 |= DS4_BTN_PS
        report[7] = byte7 | ((self._counter << 2) & 0xFC)

        report[8] = self._triggers[0]  # L2
        report[9] = self._triggers[1]  # R2

        # [10..11] timestamp, [12] battery high nibble + cable state
        _batt10 = round(read_battery_percent() / 10.0)
        report[12] = 0x10 | _batt10  # cable bit (bit4) + battery level

        # [30] battery level (low nibble) + plugged (bit4)
        report[30] = 0x10 | _batt10  # plugged + battery level

        self._counter = (self._counter + 1) & 0x3F
        return bytes(report)
